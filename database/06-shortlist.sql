-- Customer shortlist stories #34-36. Creates the shortlist_item table.
-- Run after 01-accounts-and-sessions.sql and 02-projects-and-images.sql.
-- Review it, then run it in the Supabase SQL Editor.
-- It only adds one new table. It does not change any existing table or data.
BEGIN;

-- One row means: this Customer saved this project.
CREATE TABLE IF NOT EXISTS public.shortlist_item (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- If the account or the project is deleted, its shortlist rows go too.
  customer_account_id INTEGER NOT NULL REFERENCES public.user_account(id) ON DELETE CASCADE,
  project_id INTEGER NOT NULL REFERENCES public.interior_design_project(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  -- Each Customer can save each project only once.
  CONSTRAINT shortlist_item_customer_project_unique UNIQUE (customer_account_id, project_id)
);

-- Keep the table private. Only the backend reads and writes it.
ALTER TABLE public.shortlist_item ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.shortlist_item FROM anon, authenticated;

COMMIT;

-- Verify after applying: the table must expose the columns below.
SELECT column_name, data_type
FROM information_schema.columns
WHERE table_schema = 'public' AND table_name = 'shortlist_item'
ORDER BY ordinal_position;
