-- Interior Designer current and past IDPs (#20-29).
-- Review this file, then run it once in the Supabase SQL Editor.
-- It adds new tables. It does not alter or seed existing account data.

BEGIN;

DO $$
BEGIN
  IF to_regclass('public.user_profile') IS NULL THEN
    RAISE EXCEPTION 'Create the existing public.user_profile table before this schema.';
  END IF;
  IF to_regclass('public.user_account') IS NULL THEN
    RAISE EXCEPTION 'Create the existing public.user_account table before this schema.';
  END IF;
END
$$;

CREATE TABLE IF NOT EXISTS public.user_session (
  id UUID PRIMARY KEY,
  account_id INTEGER NOT NULL REFERENCES public.user_account(id) ON DELETE CASCADE,
  token_hash VARCHAR(64) NOT NULL UNIQUE,
  csrf_token VARCHAR(64) NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS user_session_account_expiry_idx
  ON public.user_session (account_id, expires_at);

CREATE TABLE IF NOT EXISTS public.interior_design_project (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  description TEXT,
  property_type VARCHAR(80),
  design_style VARCHAR(80),
  status VARCHAR(16) NOT NULL CHECK (status IN ('current', 'past')),
  completion_date DATE,
  designer_account_id INTEGER NOT NULL REFERENCES public.user_account(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT interior_design_project_completion_check CHECK (
    (status = 'past' AND completion_date IS NOT NULL)
    OR (status = 'current' AND completion_date IS NULL)
  )
);

CREATE INDEX IF NOT EXISTS idp_owner_status_updated_idx
  ON public.interior_design_project (designer_account_id, status, updated_at DESC);
CREATE INDEX IF NOT EXISTS idp_owner_status_completion_idx
  ON public.interior_design_project (designer_account_id, status, completion_date);
CREATE INDEX IF NOT EXISTS idp_owner_status_name_idx
  ON public.interior_design_project (designer_account_id, status, name);

CREATE TABLE IF NOT EXISTS public.project_image (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES public.interior_design_project(id) ON DELETE CASCADE,
  storage_path VARCHAR(512) NOT NULL UNIQUE,
  file_name VARCHAR(255) NOT NULL,
  content_type VARCHAR(80) NOT NULL CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
  size_bytes INTEGER NOT NULL CHECK (size_bytes BETWEEN 1 AND 5242880),
  alt_text VARCHAR(240) NOT NULL,
  sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS project_image_order_idx
  ON public.project_image (project_id, sort_order);

CREATE TABLE IF NOT EXISTS public.idp_image_upload_intent (
  id UUID PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES public.interior_design_project(id) ON DELETE CASCADE,
  designer_account_id INTEGER NOT NULL REFERENCES public.user_account(id) ON DELETE CASCADE,
  storage_path VARCHAR(512) NOT NULL UNIQUE,
  file_name VARCHAR(255) NOT NULL,
  content_type VARCHAR(80) NOT NULL CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
  size_bytes INTEGER NOT NULL CHECK (size_bytes BETWEEN 1 AND 5242880),
  alt_text VARCHAR(240) NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idp_upload_intent_owner_expiry_idx
  ON public.idp_image_upload_intent (designer_account_id, expires_at);

CREATE TABLE IF NOT EXISTS public.idp_image_cleanup_task (
  id UUID PRIMARY KEY,
  designer_account_id INTEGER NOT NULL,
  storage_path VARCHAR(512) NOT NULL UNIQUE,
  attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  last_error VARCHAR(500),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idp_image_cleanup_created_idx
  ON public.idp_image_cleanup_task (created_at);

-- The application uses its server database connection. Browser users must not
-- read or write these tables through the Supabase Data API.
ALTER TABLE public.user_session ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.interior_design_project ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.project_image ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.idp_image_upload_intent ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.idp_image_cleanup_task ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE
  public.user_session,
  public.interior_design_project,
  public.project_image,
  public.idp_image_upload_intent,
  public.idp_image_cleanup_task
FROM anon, authenticated;

COMMIT;
