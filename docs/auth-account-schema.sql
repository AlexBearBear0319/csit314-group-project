-- Account roles, registration and server-side sessions.
-- Review the audit queries before running this in Supabase SQL Editor.
-- This script does not reset passwords, change account roles or delete accounts.

BEGIN;

DO $$
BEGIN
  IF to_regclass('public.user_profile') IS NULL THEN
    CREATE TABLE public.user_profile (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name VARCHAR(100) NOT NULL,
      description TEXT,
      status VARCHAR(20) NOT NULL DEFAULT 'active',
      "createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  ELSE
    IF NOT EXISTS (
      SELECT 1 FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = 'user_profile' AND column_name = 'id'
    ) OR NOT EXISTS (
      SELECT 1 FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = 'user_profile' AND column_name = 'name'
    ) THEN
      RAISE EXCEPTION 'public.user_profile must have id and name columns.';
    END IF;
    ALTER TABLE public.user_profile ADD COLUMN IF NOT EXISTS description TEXT;
    ALTER TABLE public.user_profile ADD COLUMN IF NOT EXISTS status VARCHAR(20) NOT NULL DEFAULT 'active';
    ALTER TABLE public.user_profile ADD COLUMN IF NOT EXISTS "createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW();
    ALTER TABLE public.user_profile ADD COLUMN IF NOT EXISTS "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW();
  END IF;

  IF to_regclass('public.user_account') IS NULL THEN
    CREATE TABLE public.user_account (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username VARCHAR(64) NOT NULL,
      password VARCHAR(255) NOT NULL,
      name VARCHAR(100) NOT NULL,
      email VARCHAR(254) NOT NULL,
      dob DATE,
      photo TEXT,
      status VARCHAR(20) NOT NULL DEFAULT 'active',
      "profileId" INTEGER NOT NULL REFERENCES public.user_profile(id),
      "createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  ELSE
    IF NOT EXISTS (
      SELECT 1 FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = 'user_account' AND column_name = 'id'
    ) OR NOT EXISTS (
      SELECT 1 FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = 'user_account' AND column_name = 'username'
    ) OR NOT EXISTS (
      SELECT 1 FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = 'user_account' AND column_name = 'password'
    ) OR NOT EXISTS (
      SELECT 1 FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = 'user_account' AND column_name = 'name'
    ) THEN
      RAISE EXCEPTION 'public.user_account must have id, username, password and name columns.';
    END IF;
    -- Existing account values stay as they are. New fields remain NULL where
    -- old rows need a person to supply the right value.
    ALTER TABLE public.user_account ADD COLUMN IF NOT EXISTS email VARCHAR(254);
    ALTER TABLE public.user_account ADD COLUMN IF NOT EXISTS dob DATE;
    ALTER TABLE public.user_account ADD COLUMN IF NOT EXISTS photo TEXT;
    ALTER TABLE public.user_account ADD COLUMN IF NOT EXISTS status VARCHAR(20) NOT NULL DEFAULT 'active';
    ALTER TABLE public.user_account ADD COLUMN IF NOT EXISTS "profileId" INTEGER;
    ALTER TABLE public.user_account ADD COLUMN IF NOT EXISTS "createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW();
    ALTER TABLE public.user_account ADD COLUMN IF NOT EXISTS "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW();
  END IF;
END
$$;

DO $$
DECLARE
  role_row RECORD;
  role_count INTEGER;
BEGIN
  FOR role_row IN
    SELECT * FROM (VALUES
      ('User Admin', 'Can manage user accounts and roles.'),
      ('Interior Designer', 'Can manage interior design projects.'),
      ('Customer', 'Can view and shortlist design projects.'),
      ('Platform Manager', 'Can manage platform categories and reports.')
    ) AS required_roles(name, description)
  LOOP
    SELECT COUNT(*) INTO role_count
    FROM public.user_profile
    WHERE LOWER(BTRIM(name)) = LOWER(role_row.name);

    IF role_count > 1 THEN
      RAISE NOTICE 'More than one profile matches role %. Review the duplicate profile query before sign-up.', role_row.name;
      CONTINUE;
    ELSIF role_count = 0 THEN
      INSERT INTO public.user_profile (name, description, status)
      VALUES (role_row.name, role_row.description, 'active');
    END IF;
  END LOOP;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.user_account'::regclass
      AND conname = 'user_account_profileId_fkey'
  ) THEN
    ALTER TABLE public.user_account
      ADD CONSTRAINT user_account_profileId_fkey
      FOREIGN KEY ("profileId") REFERENCES public.user_profile(id) NOT VALID;
  END IF;
END
$$;

CREATE TABLE IF NOT EXISTS public.user_session (
  id UUID PRIMARY KEY,
  account_id INTEGER NOT NULL REFERENCES public.user_account(id) ON DELETE CASCADE,
  token_hash VARCHAR(64) NOT NULL UNIQUE,
  csrf_token VARCHAR(64) NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS user_session_account_expiry_idx
  ON public.user_session (account_id, expires_at);

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM public.user_profile
    GROUP BY LOWER(BTRIM(name)) HAVING COUNT(*) > 1
  ) THEN
    RAISE NOTICE 'Not creating the role-name index. Resolve duplicate role names first.';
  ELSE
    CREATE UNIQUE INDEX IF NOT EXISTS user_profile_name_lower_key
      ON public.user_profile (LOWER(BTRIM(name)));
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.user_account
    WHERE username IS NOT NULL
    GROUP BY LOWER(BTRIM(username)) HAVING COUNT(*) > 1
  ) THEN
    RAISE NOTICE 'Not creating the user ID index. Review the duplicate user IDs in the audit query.';
  ELSE
    CREATE UNIQUE INDEX IF NOT EXISTS user_account_username_lower_key
      ON public.user_account (LOWER(BTRIM(username)));
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.user_account
    WHERE email IS NOT NULL AND BTRIM(email) <> ''
    GROUP BY LOWER(BTRIM(email)) HAVING COUNT(*) > 1
  ) THEN
    RAISE NOTICE 'Not creating the email index. Review the duplicate emails in the audit query.';
  ELSE
    CREATE UNIQUE INDEX IF NOT EXISTS user_account_email_lower_key
      ON public.user_account (LOWER(BTRIM(email)))
      WHERE email IS NOT NULL AND BTRIM(email) <> '';
  END IF;
END
$$;

-- Find existing rows that need a safe, human decision before first login.
SELECT
  account.id,
  account.username,
  account.email,
  account."profileId",
  profile.name AS role_name,
  account.status AS account_status,
  profile.status AS profile_status,
  CASE WHEN account.password ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$' THEN TRUE ELSE FALSE END AS has_bcrypt_password
FROM public.user_account AS account
LEFT JOIN public.user_profile AS profile ON profile.id = account."profileId"
WHERE account.username IS NULL
   OR BTRIM(account.username) = ''
   OR account.password IS NULL
   OR BTRIM(account.name) = ''
   OR account.email IS NULL
   OR BTRIM(account.email) = ''
   OR account."profileId" IS NULL
   OR account.status IS DISTINCT FROM 'active'
   OR profile.id IS NULL
   OR profile.status IS DISTINCT FROM 'active'
   OR LOWER(BTRIM(profile.name)) NOT IN ('user admin', 'interior designer', 'customer', 'platform manager')
   OR account.password !~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$'
ORDER BY account.id;

-- Review duplicate role rows. Sign-up stops for any role with more than one active match.
SELECT LOWER(BTRIM(name)) AS normalized_role_name, ARRAY_AGG(id ORDER BY id) AS profile_ids
FROM public.user_profile
GROUP BY LOWER(BTRIM(name))
HAVING COUNT(*) > 1
ORDER BY normalized_role_name;

-- Review case-insensitive duplicates before the unique indexes can be created.
SELECT 'user ID' AS field, LOWER(BTRIM(username)) AS normalized_value, ARRAY_AGG(id ORDER BY id) AS account_ids
FROM public.user_account
WHERE username IS NOT NULL
GROUP BY LOWER(BTRIM(username)) HAVING COUNT(*) > 1
UNION ALL
SELECT 'email', LOWER(BTRIM(email)), ARRAY_AGG(id ORDER BY id)
FROM public.user_account
WHERE email IS NOT NULL AND BTRIM(email) <> ''
GROUP BY LOWER(BTRIM(email)) HAVING COUNT(*) > 1;

ALTER TABLE public.user_profile ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_account ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_session ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.user_profile, public.user_account, public.user_session FROM anon, authenticated;

COMMIT;
