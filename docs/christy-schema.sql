-- Review and execute in Supabase SQL Editor; this script has not been applied remotely.
BEGIN;
-- The existing auth schema uses VARCHAR(100); forms and controllers accept 255.
-- Widen only. Keep existing values, account links, role indexes and RLS intact.
ALTER TABLE public.user_profile ALTER COLUMN name TYPE VARCHAR(255);
CREATE TABLE IF NOT EXISTS public.idp_category (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL UNIQUE,
  description VARCHAR(255) NOT NULL DEFAULT '',
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE public.idp_category ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.idp_category FROM anon, authenticated;
COMMIT;

-- Verify after applying: both tables must expose the fields below.
SELECT table_name, column_name, data_type, character_maximum_length
FROM information_schema.columns
WHERE table_schema = 'public' AND table_name IN ('user_profile', 'idp_category')
ORDER BY table_name, ordinal_position;
